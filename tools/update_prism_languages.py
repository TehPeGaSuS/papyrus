#!/usr/bin/env python3
"""Regenerate prism_languages.json: every language Prism offers, with its SRI hash.

Papyrus loads Prism from cdnjs and pins every script with an `integrity` hash. This
writes the data the server needs to do that for any language: each component's title,
aliases, the components it requires, and the cdnjs SRI hash of its .min.js file.

    python3 tools/update_prism_languages.py            # Prism 1.29.0, the version base.html uses
    python3 tools/update_prism_languages.py 1.30.0     # after bumping the version in base.html

Sources: the cdnjs API for the SRI hashes, and Prism's own components.json (from the
npm package on jsDelivr, since cdnjs doesn't carry it) for titles and dependencies.
"""
import json
import os
import sys
import urllib.request

VERSION = sys.argv[1] if len(sys.argv) > 1 else '1.29.0'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'prism_languages.json')

# Languages that prism.min.js on cdnjs (the npm package's prism.js) already contains.
CORE_LANGUAGES = ['markup', 'css', 'clike', 'javascript']


def fetch_json(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'papyrus-prism-update'})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def as_list(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def main():
    sri = fetch_json(f'https://api.cdnjs.com/libraries/prism/{VERSION}?fields=sri')['sri']
    components = fetch_json(f'https://cdn.jsdelivr.net/npm/prismjs@{VERSION}/components.json')['languages']

    languages = {}
    for lang_id, info in components.items():
        if lang_id == 'meta':
            continue
        path = f'components/prism-{lang_id}.min.js'
        if path not in sri:
            sys.exit(f'cdnjs has no SRI hash for {path}; refusing to write a partial file')
        aliases = as_list(info.get('alias'))
        alias_titles = info.get('aliasTitles') or {}
        languages[lang_id] = {
            'title': info['title'],
            'aliases': aliases,
            'alias_titles': {alias: alias_titles[alias] for alias in aliases if alias in alias_titles},
            'require': as_list(info.get('require')),
            'sri': sri[path],
        }

    for lang_id, entry in languages.items():
        for dep in entry['require']:
            if dep not in languages:
                sys.exit(f'{lang_id} requires unknown component {dep}')

    data = {
        '_comment': 'Generated by tools/update_prism_languages.py; do not edit by hand.',
        'version': VERSION,
        'core_sri': sri['prism.min.js'],
        'core_languages': CORE_LANGUAGES,
        'languages': dict(sorted(languages.items())),
    }
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print(f'Wrote {len(languages)} Prism {VERSION} languages to {OUT}')


if __name__ == '__main__':
    main()
